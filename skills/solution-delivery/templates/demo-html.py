#!/usr/bin/env python3
"""demo-html.py - 生成单文件离线可用的演示 HTML 原型(深色科技风)。

用法:
  python3 demo-html.py OUTPUT.html --title "客户门户 Demo" \
    --sections "登录:账号密码登录" "控制台:资源概览卡片" "监控:实时图表"
"""
import argparse
import html


def esc(s):
    return html.escape(s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("output")
    ap.add_argument("--title", default="Demo")
    ap.add_argument("--sections", nargs="*", default=[])
    args = ap.parse_args()

    cards = []
    for s in args.sections:
        name, _, desc = s.partition(":")
        cards.append(f"""
    <section class="card">
      <h2>{esc(name)}</h2>
      <p class="desc">{esc(desc or '演示内容占位')}</p>
      <div class="placeholder">▶ 此处为交互演示区</div>
    </section>""")

    page = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(args.title)}</title>
<style>
  * {{ box-sizing: border-box; margin: 0; padding: 0; }}
  body {{ font-family: -apple-system, "PingFang SC", "Microsoft YaHei", sans-serif;
         background: #0d1117; color: #e6edf3; line-height: 1.6; }}
  header {{ background: linear-gradient(90deg,#1f6feb,#8957e5); padding: 24px 32px; }}
  header h1 {{ font-size: 24px; }}
  .wrap {{ max-width: 1100px; margin: 0 auto; padding: 32px; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(280px,1fr)); gap: 20px; }}
  .card {{ background: #161b22; border: 1px solid #30363d; border-radius: 12px; padding: 20px; }}
  .card h2 {{ color: #58a6ff; font-size: 18px; margin-bottom: 8px; }}
  .desc {{ color: #8b949e; font-size: 14px; margin-bottom: 14px; }}
  .placeholder {{ background: #0d1117; border: 1px dashed #30363d; border-radius: 8px;
                 padding: 28px; text-align: center; color: #6e7681; }}
  footer {{ text-align: center; color: #6e7681; font-size: 12px; padding: 24px; }}
</style>
</head>
<body>
<header><h1>{esc(args.title)}</h1></header>
<main class="wrap">
  <div class="grid">
    {''.join(cards)}
  </div>
</main>
<footer>Generated by Hermes solution-delivery skill · 离线可用</footer>
</body>
</html>"""
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(page)
    print(f"[ok] 已生成演示页: {args.output}  (板块 {len(args.sections)} 个)")


if __name__ == "__main__":
    main()
